    echo '<span class="discount">' . $off . '% OFF</span>';
    echo '<span class="stock-badge ' . $badgeClass . '">' . $stockStr . '</span>';
    echo '<button class="heart" onclick="event.stopPropagation()">♡</button></div>';
    
    echo '<div class="product-details">';
    echo '<small>' . htmlspecialchars($p["category"]) . '</small>';
    echo '<h3>' . htmlspecialchars($p["name"]) . '</h3>';
    echo '<p class="rating">★ ' . $p["rating"] . ' <i>|</i> <span>1k+ ratings</span></p>';
    echo '<div class="price"><strong>₹' . number_format($p["price"]) . '</strong><del>₹' . number_format($p["mrp"]) . '</del><em>' . $off . '% off</em></div>';
    echo '<button class="add" data-id="' . $p["id"] . '" onclick="event.stopPropagation(); alert(\'Added to cart!\')" ' . $disabled . '>' . $btnText . '</button>';
    echo '</div></article>';
}

