    else $stockStr = "In Stock";
    
    $btnText = $stock === 0 ? "Out of stock" : "Add to cart <b>+</b>";
    $disabled = $stock === 0 ? "disabled" : "";
    $badgeClass = $stock === 0 ? "out-stock" : ($stock < 5 ? "low-stock" : "in-stock");
    
    echo '<article class="card" data-category="' . $p["category"] . '" data-name="' . htmlspecialchars(strtolower($p["name"] . " " . $p["category"])) . '" onclick="openProduct(' . $p["id"] . ')">';
